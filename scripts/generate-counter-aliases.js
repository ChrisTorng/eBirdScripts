// Keep the standalone counter's compatibility table tied to the actual assistant.
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const context = { document: { readyState: 'loading', addEventListener() {} } };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root, 'EBirdTextInputAssistant.user.js'), 'utf8'), context);
fs.mkdirSync(path.join(root, 'counter'), { recursive: true });
fs.writeFileSync(path.join(root, 'counter/aliases.mjs'), '// Generated by scripts/generate-counter-aliases.js; do not edit.\nexport default ' + JSON.stringify(context.__ebirdTextInputAssistant.speciesAliases, null, 2) + ';\n');
